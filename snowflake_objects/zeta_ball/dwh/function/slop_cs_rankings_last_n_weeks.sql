-- Rankings over the last N weeks of the most recent season in MATCHUPS_CROSSJOIN
CREATE OR REPLACE FUNCTION DWH.SLOP_CS_RANKINGS_LAST_N_WEEKS(WEEKS_BACK NUMBER)
RETURNS TABLE(
    LEAGUE_START_YEAR NUMBER,
    TEAM_1_SID NUMBER,
    TEAM_1 VARCHAR,
    MANAGER VARCHAR,
    WINS NUMBER,
    LOSSES NUMBER,
    TIES NUMBER,
    TOTAL_GAMES NUMBER,
    TOTAL_CATEGORIES_WON NUMBER,
    TOTAL_CATEGORIES_LOST NUMBER,
    TOTAL_CATEGORIES_DRAWN NUMBER,
    WIN_PERCENTAGE NUMBER(23,5),
    CAT_DIFFERENTIAL VARCHAR,
    THROUGH_WEEKS NUMBER,
    WEEKS_INCLUDED ARRAY
)
AS
$$
WITH CURRENT_SEASON AS (
    SELECT 
        MAX(LEAGUE_START_YEAR) AS LEAGUE_START_YEAR,
        MAX(WEEK_NUMBER) AS MAX_WEEK
    FROM DWH.MATCHUPS_CROSSJOIN
    WHERE LEAGUE_START_YEAR = (SELECT MAX(LEAGUE_START_YEAR) FROM DWH.MATCHUPS_CROSSJOIN)
)
SELECT 
    M.LEAGUE_START_YEAR,
    M.TEAM_1_SID,
    ANY_VALUE(T.YAHOO_TEAM_NAME) AS TEAM_1,
    ANY_VALUE(T.MANAGER) AS MANAGER,
    SUM(
        CASE WHEN M.TEAM_1_RESULT = 'W' THEN 1 ELSE 0 END
    ) AS WINS, 
    SUM(
        CASE WHEN M.TEAM_1_RESULT = 'L' THEN 1 ELSE 0 END
    ) AS LOSSES,
    SUM(
        CASE WHEN M.TEAM_1_RESULT = 'T' THEN 1 ELSE 0 END
    ) AS TIES,
    COUNT(*) AS TOTAL_GAMES,
    SUM(
        M.CATEGORIES_WON_BY_TEAM_1
    ) AS TOTAL_CATEGORIES_WON,
    SUM(
        M.CATEGORIES_WON_BY_TEAM_2
    ) AS TOTAL_CATEGORIES_LOST,
    SUM(
        9 - (M.CATEGORIES_WON_BY_TEAM_1 + M.CATEGORIES_WON_BY_TEAM_2)
    ) AS TOTAL_CATEGORIES_DRAWN,

    ROUND((WINS + (TIES * 0.5) ) / TOTAL_GAMES, 5) AS WIN_PERCENTAGE,

    concat(TOTAL_CATEGORIES_WON, '-', TOTAL_CATEGORIES_LOST, '-', TOTAL_CATEGORIES_DRAWN) AS CAT_DIFFERENTIAL,

    MAX(M.WEEK_NUMBER) AS THROUGH_WEEKS,
    ARRAY_AGG(DISTINCT M.WEEK_NUMBER) AS WEEKS_INCLUDED

FROM DWH.MATCHUPS_CROSSJOIN M
INNER JOIN CURRENT_SEASON CS
    ON M.LEAGUE_START_YEAR = CS.LEAGUE_START_YEAR
INNER JOIN DWH.TEAMS_FULL T
    ON T.TEAM_SID = M.TEAM_1_SID
WHERE M.WEEK_NUMBER > CS.MAX_WEEK - WEEKS_BACK
GROUP BY M.LEAGUE_START_YEAR, M.TEAM_1_SID
ORDER BY WIN_PERCENTAGE DESC
$$;
