CREATE OR REPLACE VIEW DWH.TEAMS_FULL AS
SELECT 
    T.TEAM_SID,
    LM.LEAGUE_MEMBER_SID,
    LM.MANAGER,
    T.YAHOO_TEAM_NAME,
    L.LEAGUE_START_YEAR,
    L.YAHOO_NBA_SEASON_KEY,
    L.YAHOO_LEAGUE_KEY,
    L.YAHOO_NBA_SEASON_KEY || '.l.' || L.YAHOO_LEAGUE_KEY || '.t.' || T.YAHOO_TEAM_ID AS YAHOO_TEAM_KEY
FROM DWH.TEAMS T 
INNER JOIN DWH.LEAGUE_MEMBERS LM ON T.LEAGUE_MEMBER_SID = LM.LEAGUE_MEMBER_SID
INNER JOIN DWH.LEAGUES L ON L.LEAGUE_START_YEAR = T.LEAGUE_START_YEAR
; 