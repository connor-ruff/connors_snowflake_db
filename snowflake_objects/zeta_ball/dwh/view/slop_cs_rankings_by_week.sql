-- Cumulative SlopCS standings as of the end of each week (one row per season, week, team).
-- Same math as DWH.SLOP_CS_RANKINGS, but repeated for every week so rank movement and history can be shown.
CREATE OR REPLACE VIEW DWH.SLOP_CS_RANKINGS_BY_WEEK AS
WITH WEEKS AS (
    SELECT DISTINCT LEAGUE_START_YEAR, WEEK_NUMBER AS THROUGH_WEEK
    FROM DWH.MATCHUPS_CROSSJOIN
),
STANDINGS AS (
    SELECT
        W.LEAGUE_START_YEAR,
        W.THROUGH_WEEK,
        M.TEAM_1_SID AS TEAM_SID,
        SUM(
            CASE WHEN M.TEAM_1_RESULT = 'W' THEN 1 ELSE 0 END
        ) AS WINS,
        SUM(
            CASE WHEN M.TEAM_1_RESULT = 'L' THEN 1 ELSE 0 END
        ) AS LOSSES,
        SUM(
            CASE WHEN M.TEAM_1_RESULT = 'T' THEN 1 ELSE 0 END
        ) AS TIES,
        COUNT(*) AS TOTAL_GAMES,
        SUM(
            M.CATEGORIES_WON_BY_TEAM_1
        ) AS TOTAL_CATEGORIES_WON,
        SUM(
            M.CATEGORIES_WON_BY_TEAM_2
        ) AS TOTAL_CATEGORIES_LOST,
        SUM(
            9 - (M.CATEGORIES_WON_BY_TEAM_1 + M.CATEGORIES_WON_BY_TEAM_2)
        ) AS TOTAL_CATEGORIES_DRAWN,

        ROUND((WINS + (TIES * 0.5) ) / TOTAL_GAMES, 5) AS WIN_PERCENTAGE
    FROM WEEKS W
    INNER JOIN DWH.MATCHUPS_CROSSJOIN M
        ON M.LEAGUE_START_YEAR = W.LEAGUE_START_YEAR
        AND M.WEEK_NUMBER <= W.THROUGH_WEEK
    GROUP BY W.LEAGUE_START_YEAR, W.THROUGH_WEEK, M.TEAM_1_SID
)
SELECT
    S.LEAGUE_START_YEAR,
    S.THROUGH_WEEK,
    S.TEAM_SID,
    T.YAHOO_TEAM_NAME AS TEAM,
    T.MANAGER,
    S.WINS,
    S.LOSSES,
    S.TIES,
    S.TOTAL_GAMES,
    S.TOTAL_CATEGORIES_WON,
    S.TOTAL_CATEGORIES_LOST,
    S.TOTAL_CATEGORIES_DRAWN,
    S.WIN_PERCENTAGE,
    RANK() OVER (PARTITION BY S.LEAGUE_START_YEAR, S.THROUGH_WEEK ORDER BY S.WIN_PERCENTAGE DESC) AS SLOP_CS_RANK
FROM STANDINGS S
INNER JOIN DWH.TEAMS_FULL T
    ON T.TEAM_SID = S.TEAM_SID
;
