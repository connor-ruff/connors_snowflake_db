-- Cumulative SlopCS standings as of the end of each week (one row per season, week, team).
-- Same math as DWH.SLOP_CS_RANKINGS, but repeated for every week so rank movement and history can be shown.
CREATE OR REPLACE VIEW DWH.SLOP_CS_RANKINGS_BY_WEEK AS
WITH WEEKS AS (
    SELECT DISTINCT LEAGUE_START_YEAR, WEEK_NUMBER AS THROUGH_WEEK
    FROM DWH.MATCHUPS_CROSSJOIN
),
STANDINGS AS (
    SELECT
        W.LEAGUE_START_YEAR,
        W.THROUGH_WEEK,
        M.TEAM_1_SID AS TEAM_SID,
        SUM(
            CASE WHEN M.TEAM_1_RESULT = 'W' THEN 1 ELSE 0 END
        ) AS WINS,
        SUM(
            CASE WHEN M.TEAM_1_RESULT = 'L' THEN 1 ELSE 0 END
        ) AS LOSSES,
        SUM(
            CASE WHEN M.TEAM_1_RESULT = 'T' THEN 1 ELSE 0 END
        ) AS TIES,
        COUNT(*) AS TOTAL_GAMES,
        SUM(
            M.CATEGORIES_WON_BY_TEAM_1
        ) AS TOTAL_CATEGORIES_WON,
        SUM(
            M.CATEGORIES_WON_BY_TEAM_2
        ) AS TOTAL_CATEGORIES_LOST,
        SUM(
            9 - (M.CATEGORIES_WON_BY_TEAM_1 + M.CATEGORIES_WON_BY_TEAM_2)
        ) AS TOTAL_CATEGORIES_DRAWN,

        ROUND((WINS::NUMBER(38,6) + (TIES::NUMBER(38,6) * 0.5::NUMBER(38,6)) ) / TOTAL_GAMES::NUMBER(38,6), 6) AS WIN_PERCENTAGE
    FROM WEEKS W
    INNER JOIN DWH.MATCHUPS_CROSSJOIN M
        ON M.LEAGUE_START_YEAR = W.LEAGUE_START_YEAR
        AND M.WEEK_NUMBER <= W.THROUGH_WEEK
    GROUP BY W.LEAGUE_START_YEAR, W.THROUGH_WEEK, M.TEAM_1_SID
),
PERCENTAGES_AND_RANKS AS (
    SELECT
        S.LEAGUE_START_YEAR,
        S.THROUGH_WEEK,
        S.TEAM_SID,
        T.YAHOO_TEAM_NAME AS TEAM,
        T.MANAGER,
        S.WINS,
        S.LOSSES,
        S.TIES,
        S.TOTAL_GAMES,
        S.TOTAL_CATEGORIES_WON,
        S.TOTAL_CATEGORIES_LOST,
        S.TOTAL_CATEGORIES_DRAWN,
        S.WIN_PERCENTAGE,
        RANK() OVER (PARTITION BY S.LEAGUE_START_YEAR, S.THROUGH_WEEK ORDER BY S.WIN_PERCENTAGE::NUMBER(38,6) DESC) AS SLOP_CS_RANK,
        ROW_NUMBER() OVER (PARTITION BY S.LEAGUE_START_YEAR, S.THROUGH_WEEK ORDER BY S.WIN_PERCENTAGE::NUMBER(38,6) DESC, S.TOTAL_CATEGORIES_WON DESC, S.TOTAL_CATEGORIES_LOST ASC, S.TEAM_SID ASC) AS SLOP_CS_RANK_NO_TIE,
        COUNT(*) OVER (PARTITION BY S.LEAGUE_START_YEAR, S.THROUGH_WEEK, S.WIN_PERCENTAGE::NUMBER(38,6)) AS NUM_TEAMS_WITH_SAME_WIN_PERCENTAGE,
        ROW_NUMBER() OVER (PARTITION BY S.LEAGUE_START_YEAR, S.THROUGH_WEEK, S.WIN_PERCENTAGE::NUMBER(38,6)  ORDER BY S.TOTAL_CATEGORIES_WON ASC, S.TOTAL_CATEGORIES_LOST DESC, S.TEAM_SID DESC) - 1 AS INV_ROW_NUMBER_WITH_SAME_WIN_PERCENTAGE
    FROM STANDINGS S
    INNER JOIN DWH.TEAMS_FULL T
        ON T.TEAM_SID = S.TEAM_SID
)
SELECT 
    LEAGUE_START_YEAR,
    THROUGH_WEEK,
    TEAM_SID,
    TEAM,
    MANAGER,
    WINS,
    LOSSES,
    TIES,
    TOTAL_GAMES,
    TOTAL_CATEGORIES_WON,
    TOTAL_CATEGORIES_LOST,
    TOTAL_CATEGORIES_DRAWN,

    WIN_PERCENTAGE,
    
    CASE WHEN NUM_TEAMS_WITH_SAME_WIN_PERCENTAGE > 1 
        THEN WIN_PERCENTAGE + ((INV_ROW_NUMBER_WITH_SAME_WIN_PERCENTAGE) * 0.00001)
    ELSE WIN_PERCENTAGE
    END AS ADJUSTED_WIN_PERCENTAGE,
    
    SLOP_CS_RANK,
    SLOP_CS_RANK_NO_TIE AS ADJUSTED_SLOP_CS_RANK,

    ROUND(WIN_PERCENTAGE * 10000, 2) AS SLOP_CS_SCORE,
    ROUND(ADJUSTED_WIN_PERCENTAGE * 10000 * 1.17, 2) AS ADJUSTED_SLOP_CS_SCORE,

    -- Pull previous week's adjusted rank, if available
    LAG(ADJUSTED_SLOP_CS_RANK) OVER (PARTITION BY LEAGUE_START_YEAR, TEAM_SID ORDER BY THROUGH_WEEK) AS PREVIOUS_ADJUSTED_SLOP_CS_RANK
FROM PERCENTAGES_AND_RANKS
;
