CREATE OR REPLACE VIEW DWH.SLOP_STAT_RANKINGS AS

SELECT 
    S.LEAGUE_START_YEAR,
    S.TEAM_SID,
    T.YAHOO_TEAM_NAME AS TEAM,
    T.MANAGER,
    S.STAT_NAME,
    S.STAT,
    CASE WHEN S.STAT_NAME = 'TO' THEN RANK() OVER (PARTITION BY S.LEAGUE_START_YEAR, S.STAT_NAME ORDER BY S.STAT)
    ELSE RANK() OVER (PARTITION BY S.LEAGUE_START_YEAR, S.STAT_NAME ORDER BY S.STAT DESC) END
     AS STAT_RANKING
FROM (
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'PTS' AS STAT_NAME,
    SUM(TOTAL_PTS)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'REB' AS STAT_NAME,
    SUM(TOTAL_REB)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'AST' AS STAT_NAME,
    SUM(TOTAL_AST)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'STL' AS STAT_NAME,
    SUM(TOTAL_STL)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'BLK' AS STAT_NAME,
    SUM(TOTAL_BLK)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    '3PM' AS STAT_NAME,
    SUM(TOTAL_THREE_PM)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'FT%' AS STAT_NAME,
    -- TEMPORARY: simple average of weekly percentages. The Walter API has no makes/attempts, so the
    -- old SUM(makes) / SUM(attempts) isn't possible; this weights every week equally.
    ROUND(AVG(FT_PCT)::NUMBER(38,6), 6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'FG%' AS STAT_NAME,
    -- TEMPORARY: simple average of weekly percentages. The Walter API has no makes/attempts, so the
    -- old SUM(makes) / SUM(attempts) isn't possible; this weights every week equally.
    ROUND(AVG(FG_PCT)::NUMBER(38,6), 6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
UNION ALL
SELECT
    LEAGUE_START_YEAR,
    TEAM_SID,
    'TO' AS STAT_NAME,
    SUM(TOTAL_TOS)::NUMBER(38,6) AS STAT
FROM DWH.WEEKLY_TEAM_TOTALS
GROUP BY LEAGUE_START_YEAR, TEAM_SID
) S
INNER JOIN DWH.TEAMS_FULL T
    ON T.TEAM_SID = S.TEAM_SID
;
