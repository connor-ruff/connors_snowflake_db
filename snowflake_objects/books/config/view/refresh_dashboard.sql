CREATE OR REPLACE VIEW CONFIG.REFRESH_DASHBOARD AS

SELECT 
    'KDP' AS SOURCE,
    MAX(ROYALTY_DATE) AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://kdpreports.amazon.com/orders' AS URL,
FROM KDP.COMBINED_SALES

UNION ALL 

SELECT 
    'KENP' AS SOURCE, 
    MAX(KENP_DATE) AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://kdpreports.amazon.com/orders' AS URL
FROM KDP.KENP

UNION ALL 

SELECT 
    'ACX' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://www.acx.com/statements' AS URL
FROM ACX.SUMMARY

UNION ALL 

SELECT 
    'INAUDIO' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://voices.inaudio.com/reporting/royalty-reports' AS URL
FROM INAUD.ROYALTY_REPORT_ALL_TABS

UNION ALL 

SELECT 
    'SPOT - ROYALTY' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://authors.spotify.com/dash/reports?tab=insights&period=Weekly' AS URL
FROM SPOT.ROYALTY_REPORT_ALL_TABS

UNION ALL 

SELECT 
    'SPOT - MONTHLY LISTENERS' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://authors.spotify.com/dash/reports?tab=insights&period=Weekly' AS URL
FROM SPOT.LISTENER_MONTHLY_REPORT

UNION ALL 

SELECT 
    'SPOT - WEEKLY LISTENERS' AS SOURCE, 
    MAX(DP_SOURCE_FILE_END_DATE) AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://authors.spotify.com/dash/reports?tab=insights&period=Weekly' AS URL
FROM SPOT.LISTENER_WEEKLY_REPORT

UNION ALL 

SELECT 
    'IG - WHOLESALE POD USD' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://myaccount.ingramspark.com/?ReturnUrl=%2FDashboard' AS URL
FROM IG.WHOLESALE_POD_USD

UNION ALL 

SELECT 
    'IG - WHOLESALE POD AUD' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://myaccount.ingramspark.com/?ReturnUrl=%2FDashboard' AS URL
FROM IG.WHOLESALE_POD_AUD

UNION ALL 

SELECT 
    'IG - WHOLESALE POD GBP' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://myaccount.ingramspark.com/?ReturnUrl=%2FDashboard' AS URL
FROM IG.WHOLESALE_POD_GBP

UNION ALL 

SELECT 
    'IG - GLOBAL CONNECT' AS SOURCE,
    LAST_DAY(MAX(DP_SOURCE_FILE_MONTH), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://myaccount.ingramspark.com/?ReturnUrl=%2FDashboard' AS URL
FROM IG.GLOBAL_CONNECT

UNION ALL 

SELECT 
    'FOREX RATES - FINAL' AS SOURCE,
    LAST_DAY(MAX(MONTH_BEGIN_DATE), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://www.x-rates.com/historical/?from=USD&amount=1&date=2026-11-27' AS URL
FROM CONFIG.FOREX_RATES
WHERE IS_FINAL = TRUE

UNION ALL 

SELECT 
    'FOREX RATES - ALL' AS SOURCE,
    LAST_DAY(MAX(MONTH_BEGIN_DATE), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://www.x-rates.com/historical/?from=USD&amount=1&date=2026-11-27' AS URL
FROM CONFIG.FOREX_RATES

UNION ALL 

SELECT 
    'KENP RATES - FINAL' AS SOURCE,
    LAST_DAY(MAX(MONTH_BEGIN_DATE), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://readerlinks.com/kenp_rates/index.php' AS URL
FROM CONFIG.KENP_RATES
WHERE IS_FINAL = TRUE

UNION ALL 

SELECT 
    'KENP RATES - ALL' AS SOURCE,
    LAST_DAY(MAX(MONTH_BEGIN_DATE), 'MONTH') AS LATEST_DATA_AVAILABLE,
    MAX(DP_LOAD_TIMESTAMP) AS LATEST_LOAD_TIMESTAMP,
    'https://readerlinks.com/kenp_rates/index.php' AS URL
FROM CONFIG.KENP_RATES
;