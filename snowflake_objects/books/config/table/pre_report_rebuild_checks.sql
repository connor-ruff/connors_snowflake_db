FROM BOOKS.KDP.COMBINED_SALES CS
WHERE NOT EXISTS (
    SELECT 1
    FROM BOOKS.CONFIG.FOREX_RATES FOREX
    WHERE FOREX.SOURCE_CURRENCY  = CS.CURRENCY
