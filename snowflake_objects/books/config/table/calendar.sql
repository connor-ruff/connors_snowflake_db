CREATE TABLE IF NOT EXISTS CONFIG.CALENDAR (
    CALENDAR_DATE DATE NOT NULL,
    YEAR INT NOT NULL,
    MONTH INT NOT NULL,
    DAY INT NOT NULL,
    PRIMARY KEY (CALENDAR_DATE)
);

TRUNCATE TABLE CONFIG.CALENDAR;

-- Insert calendar dates from 2026-01-01 to 2050-12-31 if they do not already exist
INSERT INTO CONFIG.CALENDAR (CALENDAR_DATE, YEAR, MONTH, DAY)
WITH DATES AS (
    SELECT DATEADD(DAY, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, '2026-01-01'::DATE) AS D
    FROM TABLE(GENERATOR(ROWCOUNT => 10000))
)
SELECT D, YEAR(D), MONTH(D), DAY(D)
FROM DATES
WHERE D <= '2050-12-31'
  AND NOT EXISTS (SELECT 1 FROM CONFIG.CALENDAR C WHERE C.CALENDAR_DATE = DATES.D);