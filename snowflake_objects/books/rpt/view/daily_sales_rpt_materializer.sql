        MTD_NET_PUB_COMP AS ROYALTY_IN_REPORTING_CURRENCY, 
        REPORTING_CURRENCY_CODE,
        MTD_NET_QUANTITY AS NET_UNITS_SOLD
    FROM IG.WHOLESALE_POD_AUD 
    UNION ALL 
