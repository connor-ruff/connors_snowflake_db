        MTD_NET_QUANTITY AS NET_UNITS_SOLD
    FROM IG.GLOBAL_CONNECT
),

IG_SALES_MONTHLY AS (
    SELECT 
        B.BOOK_SID,
        BV.BOOK_VERSION_SID,
        B.TITLE AS BOOK_TITLE,
        I.SALE_SOURCE,
        BV.VERSION_TYPE,
        BV.VERSION_LANGUAGE,
        I.MARKETPLACE,
        I.ROYALTY_MONTH, -- will be flattened to date
        SUM(
            ROYALTY_IN_REPORTING_CURRENCY * FOREX.EXCHANGE_RATE
        ) AS ROYALTY_IN_USD,
        SUM(NET_UNITS_SOLD) AS NET_UNITS_SOLD
    FROM IG_UNIFIED_ROWS I 
    LEFT JOIN CONFIG.BOOK_VERSIONS BV ON I.ISBN_13 = BV.BOOK_VERSION_UNIQUE_ID
    LEFT JOIN CONFIG.BOOKS B ON BV.BOOK_SID = B.BOOK_SID
    LEFT JOIN CONFIG.FOREX_RATES FOREX 
        ON I.REPORTING_CURRENCY_CODE = FOREX.SOURCE_CURRENCY
       AND  DATE_TRUNC('MONTH', I.ROYALTY_MONTH) = FOREX.MONTH_BEGIN_DATE 
    GROUP BY ALL 
),

