-- Rebuilds a single reporting table from its source view.
-- Called (in parallel, per run group) by BOOKS.RPT.BUILD_ALL_REPORTS.
CREATE OR REPLACE PROCEDURE BOOKS.RPT.REBUILD_REPORT_TABLE(SOURCE_VIEW_NAME VARCHAR, TARGET_TABLE_NAME VARCHAR)
RETURNS NUMBER
LANGUAGE SQL
AS
$$
DECLARE
    v_sql VARCHAR;
BEGIN
    v_sql := 'TRUNCATE TABLE BOOKS.' || :TARGET_TABLE_NAME;
    EXECUTE IMMEDIATE :v_sql;

    v_sql := 'INSERT INTO BOOKS.' || :TARGET_TABLE_NAME || ' SELECT * FROM BOOKS.' || :SOURCE_VIEW_NAME;
    EXECUTE IMMEDIATE :v_sql;

    RETURN SQLROWCOUNT;
END;
$$;
